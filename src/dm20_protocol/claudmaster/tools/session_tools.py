def mock_mode_warning(reason: str | None) -> str:
    """Player-facing warning shown whenever Claudmaster runs on the mock client."""
    return (
        "Claudmaster is running in MOCK MODE: narration and rulings are placeholder "
        f"text, not generated by Claude. Reason: {reason or 'unknown'}. "
        f"Fix: set ANTHROPIC_API_KEY and install the extra ({INSTALL_HINT}), "
        "then start a new session."
    )


def _rulebook_manager():
    """Current campaign's rulebook manager (for the Arbiter's get_monster_info tool)."""
    return getattr(_storage, "rulebook_manager", None) if _storage is not None else None


def set_storage(storage_instance):
    """Set the storage instance for session tools.

    Called by main.py during initialization to inject the DnDStorage instance
    so that session tools can load campaigns and access quest data.

    Args:
        storage_instance: The DnDStorage instance from main.py
    """
    global _storage
    _storage = storage_instance


